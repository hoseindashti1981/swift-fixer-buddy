const unknown = { id: "unknown", label: "نمی‌دانم / مشاهده نکرده‌ام", next: "need-evidence" };
function question(
  title: string,
  help: string,
  refs: string[],
  choices: GuideChoice[],
): GuideQuestion {
  return { kind: "question", title, help, refs, choices: [...choices, unknown] };
}
function result(
  title: string,
  explanation: string,
  nextSteps: string[],
  refs: string[],
  status: GuideResult["status"] = "check",
): GuideResult {
  return { kind: "result", title, explanation, nextSteps, refs, status };
}

