export type GuideChoice = { id: string; label: string; next: string };
export type GuideQuestion = {
  kind: "question";
  title: string;
  help: string;
  refs: string[];
  choices: GuideChoice[];
};
export type GuideResult = {
  kind: "result";
  title: string;
  status: "check" | "unknown" | "stop";
  explanation: string;
  nextSteps: string[];
  refs: string[];
};
export type GuideNode = GuideQuestion | GuideResult;
export type DiagnosticGuide = {
  id: string;
  title: string;
  description: string;
  nodes: Record<string, GuideNode>;
};

